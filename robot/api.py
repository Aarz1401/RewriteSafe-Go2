"""The only capabilities available to controller programs. Coordinates are metres/radians."""

from typing import Protocol

Pose = tuple[float, float, float]


class RobotAPI(Protocol):
    def get_robot_pose(self) -> Pose: ...
    def get_object_pose(self, name: str) -> Pose: ...
    def get_object_size(self, name: str) -> tuple[float, float, float]: ...
    def list_objects(self) -> list[str]: ...
    def set_velocity(self, vx: float, vy: float, wz: float) -> None: ...
    def drive_for(self, vx: float, vy: float, wz: float, seconds: float) -> None: ...
    def go_to(
        self, x: float, y: float, yaw: float | None = None, max_speed: float = 0.5
    ) -> None: ...
    def stop(self) -> None: ...
    def sleep(self, seconds: float) -> None: ...
    def get_top_down_image(self) -> list: ...


class RealBackend:
    """Future sport velocity + AprilTag backend. Intentionally cannot drive hardware."""

    speed_cap: float = 0.3

    def __init__(self) -> None:
        raise NotImplementedError("Hardware backend is out of scope; no SDK or network code")
